  account_holder text not null check (length(btrim(account_holder)) between 2 and 160),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  account_scope text not null check (account_scope in ('local', 'international')),
  cbu text,
  alias text,
  account_number text,
  routing_number text,
  swift_bic text,
  iban text,
  is_primary boolean not null default false,
