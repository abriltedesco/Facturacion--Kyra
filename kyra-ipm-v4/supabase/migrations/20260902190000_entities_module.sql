create table public.billing_entities (
  id bigint generated by default as identity primary key,
  name text not null check (length(btrim(name)) between 2 and 160),
  status text not null default 'active' check (status in ('active', 'inactive', 'archived')),
  legal_type text not null check (legal_type in ('srl', 'monotributista', 'llc')),
  country_code text not null check (country_code in ('AR', 'US')),
  fiscal_id_type text not null check (fiscal_id_type in ('CUIT', 'EIN')),
  fiscal_id text not null,
  fiscal_id_normalized text generated always as (regexp_replace(fiscal_id, '[^0-9]', '', 'g')) stored,
  fiscal_address text not null check (length(btrim(fiscal_address)) between 5 and 300),
  gross_income_number text,
  billing_email text check (billing_email is null or billing_email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  default_voucher text not null check (default_voucher in ('A', 'B_EXEMPT', 'C', 'LLC')),
  allows_b_exempt boolean not null default false,
  point_of_sale text,
  invoice_prefix text,
  created_by uuid references auth.users(id) on delete restrict,
  updated_by uuid references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  archived_by uuid references auth.users(id) on delete restrict,
  constraint billing_entities_fiscal_fields_check check (
    (
      legal_type in ('srl', 'monotributista')
      and country_code = 'AR'
      and fiscal_id_type = 'CUIT'
      and private.is_valid_cuit(fiscal_id)
      and point_of_sale ~ '^[0-9]{4}$'
      and invoice_prefix is null
    )
    or
    (
      legal_type = 'llc'
      and country_code = 'US'
      and fiscal_id_type = 'EIN'
      and fiscal_id ~ '^[0-9]{2}-?[0-9]{7}$'
      and point_of_sale is null
      and invoice_prefix ~ '^[A-Z0-9][A-Z0-9-]{1,11}$'
    )
  ),
  constraint billing_entities_voucher_check check (
    (legal_type = 'srl' and default_voucher = 'A')
    or (legal_type = 'srl' and allows_b_exempt and default_voucher = 'B_EXEMPT')
    or (legal_type = 'monotributista' and not allows_b_exempt and default_voucher = 'C')
    or (legal_type = 'llc' and not allows_b_exempt and default_voucher = 'LLC')
  ),
  constraint billing_entities_b_exempt_check check (not allows_b_exempt or legal_type = 'srl'),
  constraint billing_entities_archive_check check (
    (status = 'archived' and archived_at is not null and archived_by is not null)
    or (status <> 'archived' and archived_at is null and archived_by is null)
  )
);

create unique index billing_entities_active_fiscal_id_unique_idx
  on public.billing_entities (fiscal_id_type, fiscal_id_normalized)
  where status <> 'archived';
create index billing_entities_status_idx on public.billing_entities (status);
