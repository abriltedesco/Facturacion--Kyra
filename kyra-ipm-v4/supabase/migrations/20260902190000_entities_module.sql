create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_username text;
begin
  profile_username := lower(coalesce(
    nullif(new.raw_user_meta_data ->> 'username', ''),
    split_part(coalesce(new.email, ''), '@', 1)
  ));

  insert into public.profiles (user_id, username, display_name)
  values (
    new.id,
    profile_username,
    coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), profile_username)
  )
  on conflict (user_id) do update
    set username = excluded.username,
        display_name = excluded.display_name;

  return new;
end;
$$;

create trigger on_auth_user_created
after insert or update of email, raw_user_meta_data on auth.users
for each row execute function private.handle_new_user();

create or replace function public.save_billing_entity(
  p_entity jsonb,
  p_accounts jsonb default '[]'::jsonb,
  p_expected_updated_at timestamptz default null
)
returns public.billing_entities
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  entity_id bigint := nullif(p_entity ->> 'id', '')::bigint;
  account jsonb;
  account_id bigint;
  current_updated_at timestamptz;
  saved_entity public.billing_entities;
begin
  if actor is null then
    raise exception using errcode = '42501', message = 'AUTH_REQUIRED';
  end if;
  if jsonb_typeof(p_entity) <> 'object' then
    raise exception using errcode = '22023', message = 'INVALID_ENTITY_PAYLOAD';
  end if;
  if jsonb_typeof(p_accounts) <> 'array' or jsonb_array_length(p_accounts) = 0 then
    raise exception using errcode = '23514', message = 'AT_LEAST_ONE_BANK_ACCOUNT_REQUIRED';
  end if;

  if entity_id is null then
    insert into public.billing_entities (
      name, status, legal_type, country_code, fiscal_id_type, fiscal_id,
      fiscal_address, gross_income_number, billing_email, default_voucher,
      allows_b_exempt, point_of_sale, invoice_prefix, created_by, updated_by
    ) values (
      btrim(p_entity ->> 'name'),
      coalesce(nullif(p_entity ->> 'status', ''), 'active'),
      p_entity ->> 'legalType',
      p_entity ->> 'countryCode',
      p_entity ->> 'fiscalIdType',
      btrim(p_entity ->> 'fiscalId'),
      btrim(p_entity ->> 'fiscalAddress'),
      nullif(btrim(p_entity ->> 'grossIncomeNumber'), ''),
      nullif(btrim(p_entity ->> 'billingEmail'), ''),
      p_entity ->> 'defaultVoucher',
      coalesce((p_entity ->> 'allowsBExempt')::boolean, false),
      nullif(btrim(p_entity ->> 'pointOfSale'), ''),
      nullif(upper(btrim(p_entity ->> 'invoicePrefix')), ''),
      actor,
      actor
    ) returning * into saved_entity;
  else
    select updated_at into current_updated_at
    from public.billing_entities
    where id = entity_id
    for update;

    if not found then
      raise exception using errcode = 'P0002', message = 'ENTITY_NOT_FOUND';
    end if;
    if p_expected_updated_at is null or current_updated_at <> p_expected_updated_at then
      raise exception using errcode = '40001', message = 'ENTITY_VERSION_CONFLICT';
    end if;

    update public.billing_entities
    set name = btrim(p_entity ->> 'name'),
        status = coalesce(nullif(p_entity ->> 'status', ''), status),
        legal_type = p_entity ->> 'legalType',
        country_code = p_entity ->> 'countryCode',
        fiscal_id_type = p_entity ->> 'fiscalIdType',
        fiscal_id = btrim(p_entity ->> 'fiscalId'),
        fiscal_address = btrim(p_entity ->> 'fiscalAddress'),
        gross_income_number = nullif(btrim(p_entity ->> 'grossIncomeNumber'), ''),
        billing_email = nullif(btrim(p_entity ->> 'billingEmail'), ''),
        default_voucher = p_entity ->> 'defaultVoucher',
        allows_b_exempt = coalesce((p_entity ->> 'allowsBExempt')::boolean, false),
        point_of_sale = nullif(btrim(p_entity ->> 'pointOfSale'), ''),
        invoice_prefix = nullif(upper(btrim(p_entity ->> 'invoicePrefix')), ''),
        archived_at = case when coalesce(nullif(p_entity ->> 'status', ''), status) = 'archived' then now() else null end,
        archived_by = case when coalesce(nullif(p_entity ->> 'status', ''), status) = 'archived' then actor else null end,
        updated_by = actor
    where id = entity_id
    returning * into saved_entity;
  end if;

  update public.entity_bank_accounts
  set is_primary = false,
      updated_by = actor
  where entity_id = saved_entity.id and archived_at is null;

  update public.entity_bank_accounts existing
  set archived_at = now(),
      is_primary = false,
      updated_by = actor
  where existing.entity_id = saved_entity.id
    and existing.archived_at is null
    and not exists (
      select 1
      from jsonb_array_elements(p_accounts) supplied
      where nullif(supplied ->> 'id', '')::bigint = existing.id
    );

  for account in select value from jsonb_array_elements(p_accounts) loop
    account_id := nullif(account ->> 'id', '')::bigint;
    if account_id is null then
      insert into public.entity_bank_accounts (
        entity_id, bank_name, account_holder, currency, account_scope,
        cbu, alias, account_number, routing_number, swift_bic, iban,
        is_primary, created_by, updated_by
      ) values (
        saved_entity.id,
        btrim(account ->> 'bankName'),
        btrim(account ->> 'accountHolder'),
        upper(account ->> 'currency'),
        account ->> 'accountScope',
        nullif(regexp_replace(coalesce(account ->> 'cbu', ''), '[^0-9]', '', 'g'), ''),
        nullif(btrim(account ->> 'alias'), ''),
        nullif(btrim(account ->> 'accountNumber'), ''),
        nullif(btrim(account ->> 'routingNumber'), ''),
        nullif(upper(btrim(account ->> 'swiftBic')), ''),
        nullif(upper(btrim(account ->> 'iban')), ''),
        coalesce((account ->> 'isPrimary')::boolean, false),
        actor,
        actor
      );
    else
      update public.entity_bank_accounts
      set bank_name = btrim(account ->> 'bankName'),
          account_holder = btrim(account ->> 'accountHolder'),
          currency = upper(account ->> 'currency'),
          account_scope = account ->> 'accountScope',
          cbu = nullif(regexp_replace(coalesce(account ->> 'cbu', ''), '[^0-9]', '', 'g'), ''),
          alias = nullif(btrim(account ->> 'alias'), ''),
          account_number = nullif(btrim(account ->> 'accountNumber'), ''),
          routing_number = nullif(btrim(account ->> 'routingNumber'), ''),
          swift_bic = nullif(upper(btrim(account ->> 'swiftBic')), ''),
          iban = nullif(upper(btrim(account ->> 'iban')), ''),
          is_primary = coalesce((account ->> 'isPrimary')::boolean, false),
          archived_at = null,
          updated_by = actor
      where id = account_id and entity_id = saved_entity.id;

      if not found then
        raise exception using errcode = '22023', message = 'BANK_ACCOUNT_NOT_FOUND';
      end if;
    end if;
  end loop;

  return saved_entity;
end;
$$;

create or replace function public.set_billing_entity_status(
  p_entity_id bigint,
  p_status text,
  p_expected_updated_at timestamptz
)
returns public.billing_entities
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  current_updated_at timestamptz;
  saved_entity public.billing_entities;
begin
  if actor is null then
    raise exception using errcode = '42501', message = 'AUTH_REQUIRED';
  end if;
  if p_status not in ('active', 'inactive', 'archived') then
    raise exception using errcode = '22023', message = 'INVALID_ENTITY_STATUS';
  end if;

  select updated_at into current_updated_at
  from public.billing_entities
  where id = p_entity_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'ENTITY_NOT_FOUND';
  end if;
  if current_updated_at <> p_expected_updated_at then
    raise exception using errcode = '40001', message = 'ENTITY_VERSION_CONFLICT';
  end if;

  update public.billing_entities
  set status = p_status,
      archived_at = case when p_status = 'archived' then now() else null end,
      archived_by = case when p_status = 'archived' then actor else null end,
      updated_by = actor
  where id = p_entity_id
  returning * into saved_entity;

  return saved_entity;
end;
$$;

create or replace function public.register_arca_document(
  p_entity_id bigint,
  p_original_file_name text,
  p_storage_path text,
  p_expiration_date date,
  p_uploaded_by uuid
)
returns public.entity_arca_documents
language plpgsql
security definer
set search_path = ''
as $$
declare
  entity_type text;
  entity_status text;
  saved_document public.entity_arca_documents;
begin
  if auth.role() <> 'service_role' then
    raise exception using errcode = '42501', message = 'SERVICE_ROLE_REQUIRED';
  end if;

  select legal_type, status into entity_type, entity_status
  from public.billing_entities
  where id = p_entity_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'ENTITY_NOT_FOUND';
  end if;
  if entity_type = 'llc' then
    raise exception using errcode = '23514', message = 'ARCA_NOT_APPLICABLE';
  end if;
  if entity_status = 'archived' then
    raise exception using errcode = '23514', message = 'ARCHIVED_ENTITY';
  end if;

  update public.entity_arca_documents
  set superseded_at = now()
  where entity_id = p_entity_id and superseded_at is null and revoked_at is null;

  insert into public.entity_arca_documents (
    entity_id, original_file_name, storage_path, expiration_date, uploaded_by
  ) values (
    p_entity_id, btrim(p_original_file_name), p_storage_path, p_expiration_date, p_uploaded_by
  ) returning * into saved_document;

  return saved_document;
end;
$$;

create or replace function public.revoke_arca_document(
  p_document_id bigint
)
returns public.entity_arca_documents
language plpgsql
security definer
set search_path = ''
as $$
declare
  actor uuid := auth.uid();
  saved_document public.entity_arca_documents;
begin
  if actor is null then
    raise exception using errcode = '42501', message = 'AUTH_REQUIRED';
  end if;

  update public.entity_arca_documents
  set revoked_at = now(), revoked_by = actor
  where id = p_document_id and superseded_at is null and revoked_at is null
  returning * into saved_document;

  if not found then
    raise exception using errcode = 'P0002', message = 'CURRENT_DOCUMENT_NOT_FOUND';
  end if;

  return saved_document;
end;
$$;

