  updated_by uuid references public.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  constraint entity_bank_accounts_details_check check (
    (
      account_scope = 'local'
      and regexp_replace(coalesce(cbu, ''), '[^0-9]', '', 'g') ~ '^[0-9]{22}$'
      and account_number is null
      and routing_number is null
      and swift_bic is null
      and iban is null
    )
    or
    (
      account_scope = 'international'
      and length(btrim(coalesce(account_number, ''))) >= 4
      and (
        length(btrim(coalesce(routing_number, ''))) >= 4
        or swift_bic ~ '^[A-Z0-9]{8}([A-Z0-9]{3})?$'
        or length(btrim(coalesce(iban, ''))) >= 10
      )
      and cbu is null
      and alias is null
    )
  )
);

