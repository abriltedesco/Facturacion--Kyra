create table public.entity_bank_accounts (
  id bigint generated always as identity primary key,
  entity_id bigint not null references public.billing_entities(id) on delete restrict,
  bank_name text not null check (length(btrim(bank_name)) between 2 and 160),
  account_holder text not null check (length(btrim(account_holder)) between 2 and 160),
  currency text not null check (currency ~ '^[A-Z]{3}$'),
  account_scope text not null check (account_scope in ('local', 'international')),
  cbu text,
  alias text,
  account_number text,
  routing_number text,
  swift_bic text,
  iban text,
  is_primary boolean not null default false,
  created_by uuid references auth.users(id) on delete restrict,
  updated_by uuid references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  archived_at timestamptz,
  constraint entity_bank_accounts_details_check check (
    (
      account_scope = 'local'
      and regexp_replace(coalesce(cbu, ''), '[^0-9]', '', 'g') ~ '^[0-9]{22}$'
      and account_number is null
      and routing_number is null
      and swift_bic is null
      and iban is null
    )
    or
    (
      account_scope = 'international'
      and length(btrim(coalesce(account_number, ''))) >= 4
      and (
        length(btrim(coalesce(routing_number, ''))) >= 4
        or swift_bic ~ '^[A-Z0-9]{8}([A-Z0-9]{3})?$'
        or length(btrim(coalesce(iban, ''))) >= 10
      )
      and cbu is null
      and alias is null
    )
  )
);

